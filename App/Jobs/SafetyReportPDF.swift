import CNCDesign
import CNCKit
import CNCRender
import SwiftUI

/// One-page A4 safety report: toolpath preview, score, key numbers, findings
/// with fixes and the pre-flight list. Rendered with ImageRenderer as vector PDF.
@MainActor
enum SafetyReportPDF {
    static let pageSize = CGSize(width: 595, height: 842) // A4 in points

    static func make(job: JobFile, analysis: JobAnalysis, machine: Machine?) -> URL? {
        let url = FileManager.default.temporaryDirectory
            .appending(path: "\((job.name as NSString).deletingPathExtension)-safety-report.pdf")
        let renderer = ImageRenderer(content:
            ReportPage(job: job, analysis: analysis, machine: machine)
                .frame(width: pageSize.width, height: pageSize.height)
                .environment(\.colorScheme, .light)
        )
        var box = CGRect(origin: .zero, size: pageSize)
        guard let pdf = CGContext(url as CFURL, mediaBox: &box, nil) else { return nil }
        renderer.render { _, draw in
            pdf.beginPDFPage(nil)
            draw(pdf)
            pdf.endPDFPage()
        }
        pdf.closePDF()
        return url
    }
}

private struct ReportPage: View {
    let job: JobFile
    let analysis: JobAnalysis
    let machine: Machine?

    var body: some View {
        let s = analysis.statistics
        let b = analysis.document.bounds
        let items = PreflightGenerator.items(document: analysis.document, findings: analysis.findings,
                                             machine: machine?.context ?? MachineContext())
        VStack(alignment: .leading, spacing: 14) {
            HStack(alignment: .top) {
                VStack(alignment: .leading, spacing: 4) {
                    Text("Safety report").font(.system(size: 11, weight: .bold)).foregroundStyle(.secondary)
                    Text(job.name).font(.system(size: 22, weight: .bold))
                    Text(Date.now.formatted(date: .long, time: .shortened)).font(.system(size: 10)).foregroundStyle(.secondary)
                    if let machine { Text(machine.name).font(.system(size: 10)).foregroundStyle(.secondary) }
                }
                Spacer()
                ScoreBadge(score: analysis.score, hasDanger: analysis.dangerCount > 0, size: 64)
            }

            ToolpathCanvas(geometry: analysis.geometry, camera: OrbitCamera(yaw: OrbitCamera.isometric.yaw, pitch: OrbitCamera.isometric.pitch, zoom: 1.35, zScale: 3), drawProgress: 1)
                .frame(height: 250)
                .clipShape(.rect(cornerRadius: 10))

            HStack(spacing: 18) {
                fact("Est. time", Duration.seconds(s.estimatedMachiningTimeMinutes * 60).shortEstimate)
                fact("Size X × Y", "\(Int(b.width.rounded())) × \(Int(b.height.rounded())) mm")
                fact("Z range", "\(b.minZ.formatted(.number.precision(.fractionLength(1)))) … \(b.maxZ.formatted(.number.precision(.fractionLength(1)))) mm")
                fact("Moves", analysis.document.moves.count.formatted())
            }

            Text("Warnings").font(.system(size: 13, weight: .bold))
            if analysis.groups.isEmpty {
                Text("No issues found").font(.system(size: 11))
            }
            ForEach(analysis.groups.prefix(6)) { group in
                let e = Explainer.explain(group, kind: analysis.kind)
                VStack(alignment: .leading, spacing: 2) {
                    Text("\(group.severity == .danger ? "■" : "▲") \(e.title)")
                        .font(.system(size: 11, weight: .semibold))
                        .foregroundStyle(group.severity == .danger ? Color(hex: 0xDC2626) : Color(hex: 0xA16207))
                    Text(e.whatHappened).font(.system(size: 9.5))
                    Text(e.howToFix).font(.system(size: 9.5)).foregroundStyle(.secondary)
                }
            }

            Text("Pre-flight").font(.system(size: 13, weight: .bold))
            VStack(alignment: .leading, spacing: 3) {
                ForEach(items.prefix(12)) { item in
                    let t = PreflightText(item)
                    Text("☐  \(t.title)").font(.system(size: 9.5))
                }
            }
            Spacer(minLength: 0)
            Text("Generated by Toolpath. Checks and values are starting points to test, not guarantees. Always air-cut new files and wear eye and ear protection.")
                .font(.system(size: 8))
                .foregroundStyle(.secondary)
        }
        .padding(36)
        .background(Color.white)
    }

    private func fact(_ title: LocalizedStringKey, _ value: String) -> some View {
        VStack(alignment: .leading, spacing: 2) {
            Text(title).font(.system(size: 9)).foregroundStyle(.secondary)
            Text(value).font(.system(size: 12, weight: .semibold, design: .monospaced))
        }
    }
}
